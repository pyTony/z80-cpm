#!/usr/bin/env python3
"""Write z180rt.mac: uc80's runtime library with the integer and float multiplies
rewritten for the Z180's MLT instruction (8 x 8 -> 16 bits in one instruction).

    python z180/mkruntime.py [output]        (default: z180rt.mac next to this script)

Then compile with   python -m uc80.main prog.c --runtime-lib z180rt.mac --embed-lib z180.mac
(cc.ps1 -Cpu z180 does this).  The result needs a Z180; on a Z80 MLT is not an instruction.
"""
import os
import re
import subprocess
import sys

MLT_BC, MLT_DE, MLT_HL = "DB\t0EDH,4CH\t; MLT BC", "DB\t0EDH,5CH\t; MLT DE", "DB\t0EDH,6CH\t; MLT HL"

# Each routine replaces the original from its label up to the next "; ====" banner
# (or the next routine label given), keeping the surrounding library intact.
ROUTINES = {
    "__mul16": f"""__mul16:
	; Z180: HL = DE * HL (low 16 bits) with three MLTs; DE kept, A and flags changed
	PUSH	BC
	LD	B,H
	LD	C,E
	{MLT_BC}		; BC = H*E
	LD	A,C
	LD	B,D
	LD	C,L
	{MLT_BC}		; BC = D*L
	ADD	A,C
	LD	H,E
	{MLT_HL}		; HL = E*L
	ADD	A,H
	LD	H,A
	POP	BC
	RET

""",
    "__mul16_32": f"""__mul16_32:
	; Z180: DEHL = BC * DE (32 bits) with four MLTs; BC and IX kept
	PUSH	BC
	LD	H,C
	LD	L,E
	{MLT_HL}		; HL = C*E
	PUSH	HL
	LD	H,B
	LD	L,E
	{MLT_HL}		; HL = B*E
	PUSH	HL
	LD	H,C
	LD	L,D
	{MLT_HL}		; HL = C*D
	LD	E,B
	{MLT_DE}		; DE = D*B
	POP	BC
	ADD	HL,BC		; middle terms (17 bits)
	JR	NC,__m1632_nc
	INC	D
__m1632_nc:
	POP	BC		; BC = C*E
	LD	A,B
	ADD	A,L
	LD	B,A
	LD	A,E
	ADC	A,H
	LD	E,A
	LD	A,D
	ADC	A,0
	LD	D,A
	LD	H,B
	LD	L,C
	POP	BC
	RET

""",
    "__mul32": """__mul32:
	; Z180: DEHL = DEHL * (__tmp32), low 32 bits; BC and AF kept
	PUSH	AF
	PUSH	BC
	PUSH	DE		; a.hi
	PUSH	HL		; a.lo
	LD	HL,(__tmp32)
	CALL	__mul16		; HL = a.hi * b.lo (low 16)
	POP	DE		; DE = a.lo
	PUSH	HL
	LD	HL,(__tmp32+2)
	CALL	__mul16		; HL = a.lo * b.hi (low 16)
	POP	BC
	ADD	HL,BC
	PUSH	HL		; cross terms
	LD	B,D
	LD	C,E
	LD	DE,(__tmp32)
	CALL	__mul16_32	; DEHL = a.lo * b.lo
	EX	DE,HL
	POP	BC
	ADD	HL,BC
	EX	DE,HL
	INC	SP		; drop a.hi
	INC	SP
	POP	BC
	POP	AF
	RET

""",
}


def patch(src):
    for name, body in ROUTINES.items():
        m = re.search(r"^%s:\n" % re.escape(name), src, re.M)
        if not m:
            sys.exit("mkruntime: %s not found in the uc80 runtime (new uc80 version?)" % name)
        end = re.compile(r"^; =+$|^; Helper:|^\t?PUBLIC\t|^__fdiv:", re.M | re.I)
        e = end.search(src, m.end())
        if not e:
            sys.exit("mkruntime: end of %s not found" % name)
        src = src[:m.start()] + body + src[e.start():]
    return src


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "z180rt.mac")
    lib = subprocess.run([sys.executable, "-m", "uc80.main", "--print-lib-dir"],
                         capture_output=True, text=True, check=True).stdout.strip()
    with open(os.path.join(lib, "runtime.mac")) as f:
        src = f.read()
    with open(out, "w") as f:
        f.write("; Generated by z180/mkruntime.py from uc80's runtime.mac: MLT multiplies for the Z180\n")
        f.write(patch(src))
    print("wrote", out)


if __name__ == "__main__":
    main()
